import {chromium} from '../../../node_modules/playwright/index.mjs';
import fs from 'node:fs';
const dir=new URL('.',import.meta.url).pathname.replace(/^\/(?=[A-Za-z]:)/,'').replace(/\/$/,'');
fs.mkdirSync(dir+'/captures',{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1000,height:900}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto('file:///'+dir+'/index.html');
await page.waitForFunction(()=>[...document.images].every(i=>i.complete));
await page.locator('#victory-play').click();
async function scrub(t){await page.locator('#victory-time').evaluate((e,t)=>{e.value=t;e.dispatchEvent(new Event('input'))},String(t));await page.waitForTimeout(100)}
await scrub(.2);
let hash=await page.locator('canvas').evaluateAll(es=>es.map(e=>e.toDataURL()));
if(new Set(hash).size!==1)throw Error('Baseline mismatch');
await scrub(.95);
hash=await page.locator('canvas').evaluateAll(es=>es.map(e=>e.toDataURL()));
if(new Set(hash).size!==4)throw Error('Variants not distinct');
await page.screenshot({path:dir+'/captures/game-size.png',fullPage:true});
await page.locator('#victory-scale').selectOption('2');await page.screenshot({path:dir+'/captures/detail.png',fullPage:true});
await page.locator('#victory-night').check();await page.screenshot({path:dir+'/captures/night.png',fullPage:true});
const names=await page.locator('#victory-character option').allTextContents();
for(const name of names){await page.locator('#victory-character').selectOption(name);await scrub(.95)}
await page.locator('#victory-character').selectOption('Bunny');await page.locator('#victory-scale').selectOption('1');
await page.locator('input[value="Fireworks + winner zoom"]').check();
await scrub(3.4);
const camera=await page.locator('canvas').nth(1).getAttribute('data-camera');
if(Math.abs(Number(camera)-2.2)>.001)throw Error('Wrong winner zoom endpoint');
const framing=await page.locator('canvas').nth(1).evaluate(e=>({y:Number(e.dataset.offsetY),height:e.clientHeight}));
if(Math.abs(framing.y-(framing.height-framing.height*2.2))>.01)throw Error('Bottom-edge camera clamp failed');
await page.screenshot({path:dir+'/captures/winner-zoom.png',fullPage:true});
await page.setViewportSize({width:360,height:900});await page.screenshot({path:dir+'/captures/mobile.png',fullPage:true});
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Overflow');
if(errors.length)throw Error(errors.join('\n'));
console.log('PASS: shared baseline, 4 distinct variations, 19 characters, controls, night/detail, mobile; no browser errors');
await browser.close();
