let paths: readonly Path2D[] | undefined;
let stamp: OffscreenCanvas | undefined;
let stampAttempted = false;

function drawArtwork(ctx: Ctx2D): void {
  paths ??= LAYERS.map(([, path]) => new Path2D(path));
  ctx.save();
  ctx.scale(ART_SCALE, ART_SCALE);
  ctx.translate(-80, -750);
  ctx.lineJoin = 'round';
  ctx.lineCap = 'round';
  ctx.strokeStyle = INK;
  for (let i = 0; i < LAYERS.length; i++) {
    const [fill, , outline] = LAYERS[i];
    ctx.fillStyle = fill;
    ctx.fill(paths[i]);
    if (outline) {
      ctx.lineWidth = outline;
      ctx.stroke(paths[i]);
    }
  }
  ctx.restore();
}

export function drawBriar(ctx: Ctx2D): void {
  if (!stampAttempted) {
    stampAttempted = true;
    if (typeof OffscreenCanvas !== 'undefined') {
      const canvas = new OffscreenCanvas(30 * STAMP_SCALE, 17 * STAMP_SCALE);
      const bake = canvas.getContext('2d');
      if (bake) {
        bake.scale(STAMP_SCALE, STAMP_SCALE);
        bake.translate(1, 16);
        drawArtwork(bake);
        stamp = canvas;
      }
    }
  }
  if (stamp) {
    ctx.drawImage(stamp, -1, -16, 30, 17);
  } else {
    // Capability fallback remains synchronous and uses the same authored art.
    drawArtwork(ctx);
  }
}
